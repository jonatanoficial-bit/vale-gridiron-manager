import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const options = {
  url: 'https://www.nfl.com/teams/buffalo-bills/roster',
  teamId: 'nfl-buffalo-bills',
  snapshotId: 'NFL_2026_2026-10-13',
  sourceAsOfDate: '2026-10-13',
  sourceId: 'nfl-roster-buffalo-2026',
  output: 'src/data/imports/buffalo-bills-2026.ts',
}

function decodeHtml(value) {
  return value
    .replace(/&amp;/g, '&')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
}

function text(value) {
  return decodeHtml(value.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim())
}

function idFromPlayerUrl(playerUrl) {
  return playerUrl.replace(/^\/players\//, '').replace(/\/$/, '')
}

function parseRoster(html) {
  const rows = []
  const rowPattern = /<tr><td class="sorter-lastname"[\s\S]*?<a[^>]*href="([^"?]+)"[^>]*>([\s\S]*?)<\/a>[\s\S]*?<\/td><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><td class="sorter-height">([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><td>([\s\S]*?)<\/td><\/tr>/g

  for (const match of html.matchAll(rowPattern)) {
    const [, playerUrl, name, jerseyNumber, position, rosterStatus, heightIn, weightLbs, experienceLabel, college] = match
    rows.push({
      id: `nfl-2026-buffalo-bills-${idFromPlayerUrl(playerUrl)}`,
      name: text(name),
      playerUrl: `https://www.nfl.com${playerUrl}`,
      jerseyNumber: text(jerseyNumber) ? Number(text(jerseyNumber)) : null,
      position: text(position),
      rosterStatus: text(rosterStatus),
      heightIn: Number(text(heightIn)),
      weightLbs: Number(text(weightLbs)),
      experienceLabel: text(experienceLabel),
      college: text(college) || null,
    })
  }

  return rows
}

const response = await fetch(options.url, { headers: { 'user-agent': 'VALE-Gridiron-Manager roster import' } })
if (!response.ok) throw new Error(`Roster source returned HTTP ${response.status}`)

const rawHtml = await response.text()
const players = parseRoster(rawHtml)
const duplicateIds = players.filter((player, index) => players.findIndex((candidate) => candidate.id === player.id) !== index)

if (players.length < 53) throw new Error(`Expected at least 53 published roster rows, found ${players.length}`)
if (duplicateIds.length) throw new Error(`Duplicate player IDs found: ${duplicateIds.map((player) => player.id).join(', ')}`)

const sourceChecksum = createHash('sha256').update(rawHtml).digest('hex')
const typedPlayers = players.map((player) => ({
  ...player,
  teamId: options.teamId,
  seasonId: options.snapshotId,
  sourceAsOfDate: options.sourceAsOfDate,
  contentRightsStatus: 'pending',
  sourceId: options.sourceId,
  identityStatus: 'ready',
  contractStatus: 'pending',
  mediaStatus: 'pending',
  simulationAttributeStatus: 'pending',
}))

const importBatch = {
  id: 'import-nfl-buffalo-bills-2026-10-13',
  teamId: options.teamId,
  seasonId: options.snapshotId,
  sourceId: options.sourceId,
  sourceUrl: options.url,
  sourceAsOfDate: options.sourceAsOfDate,
  sourceChecksum,
  rowCount: players.length,
  duplicateCount: 0,
  importStatus: 'ready',
  notes: 'Linhas publicadas pela NFL; contratos, mídia e atributos de simulação permanecem pendentes.',
}

const moduleSource = `/* Generated by tools/import-nfl-roster.mjs from the official NFL roster page. */\nimport type { AthleteRosterRecord, RosterImportBatch } from '../../domain/roster'\n\nexport const BILLS_2026_ROSTER: AthleteRosterRecord[] = ${JSON.stringify(typedPlayers, null, 2)}\n\nexport const BILLS_2026_ROSTER_IMPORT: RosterImportBatch = ${JSON.stringify(importBatch, null, 2)}\n`

const target = resolve(options.output)
await mkdir(dirname(target), { recursive: true })
await writeFile(target, moduleSource, 'utf8')
console.log(`Imported ${players.length} roster rows to ${target}`)
